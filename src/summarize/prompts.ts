export const systemPrompt = `Ты — помощник занятого человека, который не успевает читать свои чаты в WhatsApp.
Ты получаешь расшифровку переписки и делаешь из неё выжимку на русском языке.

Жёсткие правила:
- Опирайся только на то, что есть в переписке. Ничего не додумывай и не достраивай логически.
- Сохраняй имена участников, суммы, даты, адреса, номера и названия файлов дословно.
- Если по теме не было итога, так и пиши: обсуждали, решения нет.
- Не пересказывай подряд каждое сообщение: группируй по темам.
- Пиши по-человечески и коротко, без канцелярита и без вступлений вроде «в данном чате».
- Формат ответа — Markdown.`

export function chunkPrompt(index: number, total: number, transcript: string): string {
  return `Это часть ${index} из ${total} переписки. Сделай из неё плотные рабочие заметки для последующей сборки дайджеста.

Что зафиксировать:
- обсуждаемые темы и что по каждой сказали;
- принятые решения и договорённости, с автором решения;
- вопросы и просьбы, оставшиеся без ответа;
- сроки, даты, суммы, ссылки, названия файлов;
- к кому лично обращались.

Без вступлений и без выводов — только заметки списком.

Переписка:
${transcript}`
}

export function reducePrompt(chatName: string, period: string, notes: string[]): string {
  return `Собери итоговый дайджест по чату «${chatName}» за период ${period}.
Ниже заметки по частям переписки, идущие по времени. Склей их в один связный дайджест, убрав повторы.

${notes.map((note, index) => `### Заметки, часть ${index + 1}\n${note}`).join('\n\n')}

${digestFormat}`
}

export function singlePassPrompt(chatName: string, period: string, transcript: string): string {
  return `Сделай дайджест по чату «${chatName}» за период ${period}.

Переписка:
${transcript}

${digestFormat}`
}

const digestFormat = `Формат ответа строго такой:

**Коротко:** два-три предложения о самом главном.

**О чём говорили**
- по одному пункту на тему, с сутью и участниками

**Решения и договорённости**
- что решили; если решений не было, напиши «за период решений не зафиксировано»

**Требует вашего внимания**
- вопросы и просьбы лично к вам, ближайшие сроки, всё, где ждут вашего ответа; если такого нет, напиши «прямых обращений к вам не было»

**Цифры, ссылки и файлы**
- суммы, даты, ссылки, названия файлов; если ничего не было, раздел пропусти

**Кто писал больше всех**
- имена через запятую

Без заголовка первого уровня и без завершающих комментариев о своей работе.`
